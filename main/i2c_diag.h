#ifndef I2C_DIAG_H
#define I2C_DIAG_H

#include <stdbool.h>
#include <stdint.h>

/**
 * I²C 总线诊断（用于传感器"无人应答"时的定位）。
 *
 * 目的：把「传感器没接 / 接错脚 / 缺上拉 / 地址不对 / 器件损坏」区分开。
 *
 * 关键设计：**阳性对照**。
 *   单独看到"25/26 上没有设备"无法判断是接线问题还是扫描器本身有问题，
 *   因此在启动早期（任何 I²C 驱动安装前）同时扫描已知良好的 OLED 总线
 *   （GPIO21/22，应在 0x3C 应答）。OLED 被扫到即证明扫描器工作正常，
 *   此时 25/26 扫不到任何设备就确定是接线/供电问题。
 *
 * 必须在 i2c 驱动安装前调用（诊断需独占引脚）。
 */

/** 读 SDA/SCL 空闲电平（配置为输入+内部上拉）。
 *  注意：即使不接任何器件，内部上拉也会让线为高；
 *  故"为高"只排除了线被拉死/短路，不能证明外部上拉存在。 */
void i2c_diag_lines(int sda, int scl, const char *label);

/** 单个 GPIO 的电气自检（不需要外接任何器件）。
 *
 *  做四件事并给出结论：
 *    1. 输入 + 内部上拉 → 读电平
 *    2. 输入 + 内部下拉 → 读电平
 *       **关键判据**：内部下拉约 45 kΩ；若外部有常见的 4.7 kΩ 上拉，
 *       外部上拉会压过内部下拉使读数仍为高 → 证明外部上拉确实接在本引脚上。
 *       若读为低 → 本引脚上没有外部上拉（上拉/接线没接到这里）。
 *    3. 推挽输出低 → 读回（应为 0；若为 1 说明引脚无法拉低或断路/损坏）
 *    4. 推挽输出高 → 读回（应为 1；若为 0 说明对地短路）
 *
 *  用于回答「ESP32 的这个引脚本身是否正常」以及「外部上拉是否真的在这个脚上」。
 *  返回 true 表示引脚电气行为正常。 */
bool i2c_diag_pin_selftest(int pin, const char *label);

/** 在指定引脚对上扫描 0x08–0x77，日志列出所有应答地址。
 *  label 用于区分对照对象；expect_addr 为期望地址（0 = 不检查）。
 *  返回发现的设备数（<0 表示总线打不开）。 */
int i2c_diag_scan_pair(int sda, int scl, const char *label, uint8_t expect_addr);

/** 引脚扫描：在多个常见 I2C 引脚对上查找 SHT4x（0x44 / 0x45）。
 *  用于回答「传感器到底接在哪两个脚上」——当期望引脚无应答时，
 *  本函数可自动发现传感器实际所在引脚对（或确认根本没接）。
 *  返回找到 SHT4x 的引脚对数量；找到即日志给出 SDA/SCL 与地址。 */
int i2c_diag_sweep_pins(void);

#endif /* I2C_DIAG_H */
